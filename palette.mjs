// Regenerate the palette (the library needs a bundler, its imports have no file extensions):
//   npm install --no-save @material/material-color-utilities
//   node_modules/.bin/esbuild palette.mjs --bundle --platform=node --format=esm | node --input-type=module - > .vitepress/theme/palette.css
import {
  Contrast,
  Hct,
  MaterialDynamicColors as C,
  SchemeVibrant,
  argbFromHex,
  hexFromArgb,
} from '@material/material-color-utilities'

const seed = Hct.fromInt(argbFromHex('#1E88C8'))
const gradientHues = [seed.hue - 56, seed.hue, seed.hue + 54]
const gradientChroma = 48
const gradientTone = { light: 48, dark: 76 }

const roles = {
  'primary': C.primary,
  'on-primary': C.onPrimary,
  'primary-container': C.primaryContainer,
  'on-primary-container': C.onPrimaryContainer,
  'secondary-container': C.secondaryContainer,
  'on-secondary-container': C.onSecondaryContainer,
  'tertiary': C.tertiary,
  'tertiary-container': C.tertiaryContainer,
  'on-tertiary-container': C.onTertiaryContainer,
  'error': C.error,
  'error-container': C.errorContainer,
  'on-error-container': C.onErrorContainer,
  'surface': C.surface,
  'surface-container-lowest': C.surfaceContainerLowest,
  'surface-container-low': C.surfaceContainerLow,
  'surface-container': C.surfaceContainer,
  'surface-container-high': C.surfaceContainerHigh,
  'surface-container-highest': C.surfaceContainerHighest,
  'on-surface': C.onSurface,
  'on-surface-variant': C.onSurfaceVariant,
  'outline': C.outline,
  'outline-variant': C.outlineVariant,
}

// [foreground, background, minimum WCAG ratio]; 3 is for large text and non-text parts
const pairs = [
  ['on-surface', 'surface', 4.5],
  ['on-surface-variant', 'surface', 4.5],
  ['primary', 'surface', 4.5],
  ['tertiary', 'surface', 4.5],
  ['on-primary', 'primary', 4.5],
  ['on-primary-container', 'primary-container', 4.5],
  ['on-secondary-container', 'secondary-container', 4.5],
  ['on-tertiary-container', 'tertiary-container', 4.5],
  ['tertiary', 'tertiary-container', 4.5],
  ['on-error-container', 'error-container', 4.5],
  ['error', 'error-container', 4.5],
  ['on-surface', 'surface-container-highest', 4.5],
  ['on-surface-variant', 'surface-container-highest', 4.5],
  ['primary', 'surface-container-low', 4.5],
  ['outline', 'surface', 3],
]

const tone = (hex) => Hct.fromInt(argbFromHex(hex)).tone
const ratio = (a, b) => Contrast.ratioOfTones(tone(a), tone(b))
const check = (theme, name, a, b, min) => {
  if (ratio(a, b) < min) throw new Error(`${theme}: ${name} is ${ratio(a, b).toFixed(2)}, needs ${min}`)
}

const out = ['/* Generated by palette.mjs. Do not edit single colors. */']
for (const dark of [false, true]) {
  const theme = dark ? 'dark' : 'light'
  const scheme = new SchemeVibrant(seed, dark, 0)
  const color = Object.fromEntries(
    Object.entries(roles).map(([role, c]) => [role, hexFromArgb(c.getArgb(scheme))]),
  )
  const gradient = gradientHues.map((hue) =>
    hexFromArgb(Hct.from(hue, gradientChroma, gradientTone[theme]).toInt()),
  )

  for (const [fg, bg, min] of pairs) check(theme, `${fg} on ${bg}`, color[fg], color[bg], min)
  for (const stop of gradient) check(theme, `gradient ${stop} on surface`, stop, color.surface, 3)

  out.push(dark ? '.dark {' : ':root {')
  for (const [role, hex] of Object.entries(color)) out.push(`  --md-${role}: ${hex};`)
  out.push(`  --tantal: linear-gradient(120deg, ${gradient.join(', ')});`, '}')
}
console.log(out.join('\n'))
